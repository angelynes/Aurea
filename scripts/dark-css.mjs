// Builds app/globals.generated.css from app/globals.css with automatic dark mode.
//
// Colors that come from CSS variables already switch in dark mode (see the dark
// variables at the end of globals.css). This script handles the remaining fixed
// colors: for every declaration with a literal color it adds, right after the
// rule, a `@media (prefers-color-scheme: dark)` copy with the color's lightness
// flipped (same hue), so cascade order is preserved. Shadows and dark overlays
// stay dark. Rules already inside a prefers-color-scheme block are left alone.
//
// Runs automatically before `npm run dev` and `npm run build`; edit globals.css, not the generated file.
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const SOURCE = new URL("../app/globals.css", import.meta.url);
const OUTPUT = new URL("../app/globals.generated.css", import.meta.url);
const COLOR = /#[0-9a-f]{8}\b|#[0-9a-f]{6}\b|#[0-9a-f]{3}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/gi;
const KEEP_PROPS = /shadow|^filter$|^mask/;

function parse(token) {
  const t = token.toLowerCase();
  if (t === "white") return [255, 255, 255, 1];
  if (t === "black") return [0, 0, 0, 1];
  if (t.startsWith("#")) {
    let hex = t.slice(1);
    if (hex.length === 3) hex = [...hex].map((c) => c + c).join("");
    const n = (i) => parseInt(hex.slice(i, i + 2), 16);
    return [n(0), n(2), n(4), hex.length === 8 ? n(6) / 255 : 1];
  }
  const parts = t.replace(/rgba?\(|\)/g, "").split(/[\s,/]+/).filter(Boolean).map(Number);
  return [parts[0], parts[1], parts[2], parts[3] ?? 1];
}

function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}

function fromHsl([h, s, l]) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [r, g, b].map((v) => Math.round((v + m) * 255));
}

/** Flip lightness around the middle; light surfaces become warm darks, dark text becomes light. */
function darken(token) {
  const [r, g, b, a] = parse(token);
  const [h, s, l] = toHsl([r, g, b]);
  const flipped = 0.09 + (1 - l) * 0.84;
  const sat = flipped < 0.3 ? s * 0.55 : s * 0.85;
  const [nr, ng, nb] = fromHsl([h, sat, flipped]);
  return a < 1 ? `rgba(${nr},${ng},${nb},${+a.toFixed(3)})` : `#${[nr, ng, nb].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}

function insideDarkMedia(node) {
  for (let parent = node.parent; parent; parent = parent.parent) {
    if (parent.type === "atrule" && /prefers-color-scheme/.test(parent.params)) return true;
  }
  return false;
}

const root = postcss.parse(readFileSync(SOURCE, "utf8"));
let added = 0;
root.walkRules((rule) => {
  if (insideDarkMedia(rule) || rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  // Full-screen dimmers stay dark.
  if (/backdrop|overlay/.test(rule.selector)) return;
  const decls = [];
  rule.walkDecls((decl) => {
    if (decl.prop.startsWith("--") || KEEP_PROPS.test(decl.prop)) return;
    if (!COLOR.test(decl.value)) return;
    COLOR.lastIndex = 0;
    decls.push(postcss.decl({ prop: decl.prop, value: decl.value.replace(COLOR, darken), important: decl.important }));
  });
  if (!decls.length) return;
  const media = postcss.atRule({ name: "media", params: "(prefers-color-scheme: dark)" });
  media.append(postcss.rule({ selector: rule.selector }).append(decls));
  // Inside another @media (e.g. phone layout), keep the copy inside it too.
  rule.after(media);
  added += 1;
});

writeFileSync(OUTPUT, `/* Generated by scripts/dark-css.mjs from globals.css. Do not edit. */\n${root.toString()}`);
console.log(`dark-css: ${added} rules got dark versions → app/globals.generated.css`);
